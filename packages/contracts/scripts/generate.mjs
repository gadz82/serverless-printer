import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { compile } from "json-schema-to-typescript";

const packageRoot = fileURLToPath(new URL("..", import.meta.url));
const outputDir = path.join(packageRoot, "src", "generated");

const generatedStyle = {
  bracketSpacing: true,
  printWidth: 100,
  semi: true,
  singleQuote: false,
  tabWidth: 2,
  trailingComma: "all",
  useTabs: false,
};

const schemas = [
  {
    input: "schemas/job.schema.json",
    output: "job.ts",
    typeName: "PrintJob",
  },
  {
    input: "schemas/result.schema.json",
    output: "result.ts",
    typeName: "PrintResult",
  },
];

const banner = (schemaPath) =>
  [
    "/**",
    ` * Generated from ${schemaPath} by json-schema-to-typescript.`,
    " * Do not edit this file by hand; edit the schema and regenerate.",
    " */",
  ].join("\n");

await mkdir(outputDir, { recursive: true });

for (const schema of schemas) {
  const schemaPath = path.join(packageRoot, schema.input);
  const schemaDocument = JSON.parse(await readFile(schemaPath, "utf8"));
  const source = await compile(schemaDocument, schema.typeName, {
    additionalProperties: false,
    bannerComment: banner(schema.input),
    format: true,
    style: generatedStyle,
  });
  await writeFile(path.join(outputDir, schema.output), `${source.trimEnd()}\n`, "utf8");
}
