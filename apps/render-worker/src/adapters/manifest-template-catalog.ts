import { readFileSync } from "node:fs";
import type { TemplateCatalog, TemplateDescriptor } from "@printer/domain";

export class ManifestError extends Error {
  constructor(message: string, options?: ErrorOptions) {
    super(message, options);
    this.name = "ManifestError";
  }
}

type ManifestEntry = {
  readonly id: string;
  readonly slug: string;
  readonly name: string;
  readonly path: string;
  readonly contentHash: string;
};

type TemplateManifest = {
  readonly release: string;
  readonly templates: readonly ManifestEntry[];
};

const RESERVED_SMOKE_SLUG = "_smoke";
const PUBLIC_SLUG_PATTERN = /^[a-z][a-z0-9-]{2,63}$/;
const SHA256_PATTERN = /^[0-9a-f]{64}$/;

/**
 * Resolves templates from the manifest generated by scripts/template-manifest.mjs.
 *
 * The small manifest is read and validated eagerly in the constructor so a
 * missing or corrupt bundle fails the cold-start composition, not every job.
 */
// ORCHID-MEM: 01a1c1d8-f365-7ef6-977c-6c5ee18cb802 — Resolves template ids and slugs from the bundled, content-hashed manifest.
export class ManifestTemplateCatalog implements TemplateCatalog {
  private readonly manifest: TemplateManifest;

  constructor(manifestPath: string) {
    this.manifest = readManifest(manifestPath);
  }

  async resolve(templateId: string): Promise<TemplateDescriptor | null> {
    const manifest = this.manifest;
    const entry = manifest.templates.find(
      (candidate) => candidate.id === templateId || candidate.slug === templateId,
    );

    if (entry === undefined) {
      return null;
    }

    return {
      id: entry.id,
      slug: entry.slug,
      contentHash: entry.contentHash,
      release: manifest.release,
      bundlePath: entry.path,
    };
  }
}

function readManifest(manifestPath: string): TemplateManifest {
  let source: string;
  try {
    source = readFileSync(manifestPath, "utf8");
  } catch (error) {
    throw new ManifestError(`cannot read template manifest at ${manifestPath}`, {
      cause: error,
    });
  }

  let parsed: unknown;
  try {
    parsed = JSON.parse(source);
  } catch (error) {
    throw new ManifestError(`template manifest at ${manifestPath} is not valid JSON`, {
      cause: error,
    });
  }

  try {
    return parseTemplateManifest(parsed);
  } catch (error) {
    if (error instanceof ManifestError) {
      throw new ManifestError(`invalid template manifest at ${manifestPath}: ${error.message}`, {
        cause: error,
      });
    }
    throw error;
  }
}

export function parseTemplateManifest(value: unknown): TemplateManifest {
  const manifest = asRecord(value, "manifest");
  const release = requiredString(manifest["release"], "manifest.release");
  const rawTemplates = manifest["templates"];
  if (!Array.isArray(rawTemplates)) {
    throw new ManifestError("manifest.templates must be an array");
  }

  const ids = new Set<string>();
  const slugs = new Set<string>();
  const templates: ManifestEntry[] = [];

  rawTemplates.forEach((rawEntry, index) => {
    const entry = asRecord(rawEntry, `manifest.templates[${index}]`);
    const prefix = `manifest.templates[${index}]`;
    const id = requiredString(entry["id"], `${prefix}.id`);
    const slug = requiredString(entry["slug"], `${prefix}.slug`);
    const name = requiredString(entry["name"], `${prefix}.name`);
    const path = requiredString(entry["path"], `${prefix}.path`);
    const contentHash = requiredString(entry["contentHash"], `${prefix}.contentHash`);

    assertSlug(slug, `${prefix}.slug`);
    if (!SHA256_PATTERN.test(contentHash)) {
      throw new ManifestError(`${prefix}.contentHash must be a lower-case SHA-256 hex digest`);
    }
    if (ids.has(id)) {
      throw new ManifestError(`manifest contains duplicate template id at ${prefix}`);
    }
    if (slugs.has(slug)) {
      throw new ManifestError(`manifest contains duplicate template slug at ${prefix}`);
    }

    ids.add(id);
    slugs.add(slug);
    templates.push({ id, slug, name, path, contentHash });
  });

  return { release, templates };
}

function assertSlug(slug: string, path: string): void {
  if (slug === RESERVED_SMOKE_SLUG) {
    return;
  }

  if (slug.startsWith("_")) {
    throw new ManifestError(
      `${path} may only start with an underscore for "${RESERVED_SMOKE_SLUG}"`,
    );
  }

  if (!PUBLIC_SLUG_PATTERN.test(slug)) {
    throw new ManifestError(`${path} must match ${String(PUBLIC_SLUG_PATTERN)}`);
  }
}

function asRecord(value: unknown, path: string): Record<string, unknown> {
  if (typeof value !== "object" || value === null || Array.isArray(value)) {
    throw new ManifestError(`${path} must be an object`);
  }

  return value as Record<string, unknown>;
}

function requiredString(value: unknown, path: string): string {
  if (typeof value !== "string" || value.trim().length === 0) {
    throw new ManifestError(`${path} must be a non-empty string`);
  }

  return value;
}
